#!/usr/bin/env python3
"""Generate documentation fragments from code, keeping docs/ in sync.

Reads provider metadata (supported cities, verified cities, live discovery)
straight from the provider classes and rewrites the marked sections in
docs/Providers.md. Run it after changing anything provider-related::

    python scripts/gen_docs.py

CI runs this script and fails if the working tree differs afterwards, so a
code change that alters coverage cannot merge without regenerating the docs.

Only stdlib + ``requests`` are needed (the provider modules import nothing
else at module level).
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))  # namespace-package parent lookup

# The provider modules only need stdlib + requests, but importing them
# through the real package would execute smart_fuel_price/__init__.py,
# which requires homeassistant/voluptuous. Register a lightweight package
# stub so only the modules we need are loaded.
import types

_pkg = types.ModuleType("custom_components.smart_fuel_price")
_pkg.__path__ = [str(REPO_ROOT / "custom_components" / "smart_fuel_price")]
sys.modules["custom_components.smart_fuel_price"] = _pkg

from custom_components.smart_fuel_price.const import AVAILABLE_PROVIDERS  # noqa: E402
from custom_components.smart_fuel_price.providers.affordableenergy_ca import (  # noqa: E402
    AffordableEnergyCaProvider,
)
from custom_components.smart_fuel_price.providers.base import (  # noqa: E402
    BaseFuelPriceProvider,
)
from custom_components.smart_fuel_price.providers.citynews_ca import (  # noqa: E402
    CityNewsCaProvider,
)
from custom_components.smart_fuel_price.providers.gasbuddy_ca import (  # noqa: E402
    GasBuddyStationProvider,
)
from custom_components.smart_fuel_price.providers.nrcan_gc_ca import (  # noqa: E402
    NrcanGcCaProvider,
)

PROVIDERS: list[tuple[str, type[BaseFuelPriceProvider]]] = [
    ("affordableenergy_ca", AffordableEnergyCaProvider),
    ("citynews_ca", CityNewsCaProvider),
    ("gasbuddy_ca", GasBuddyStationProvider),
    ("nrcan_gc_ca", NrcanGcCaProvider),
]

START_MARKER = "<!-- GENERATED:PROVIDER_COVERAGE:START -->"
END_MARKER = "<!-- GENERATED:PROVIDER_COVERAGE:END -->"


def _discovery_label(cls: type[BaseFuelPriceProvider]) -> str:
    # NOTE: compare via __dict__, not `cls.discover_cities is
    # BaseFuelPriceProvider.discover_cities` -- each attribute access on a
    # classmethod builds a new bound-method object, so `is` never holds.
    if "discover_cities" not in cls.__dict__:
        return "—"
    if cls is AffordableEnergyCaProvider:
        return "gaswizard.ca sitemap"
    if cls is CityNewsCaProvider:
        return "citynews.ca city switcher"
    if cls is NrcanGcCaProvider:
        return "nrcan.gc.ca city index"
    return "yes"


def build_coverage_block() -> str:
    lines = [
        START_MARKER,
        "> Auto-generated by `scripts/gen_docs.py` — do not edit by hand.",
        "",
        "| Provider | Cities (static list) | Verified with data | Live discovery |",
        "|---|---|---|---|",
    ]
    details: list[str] = []
    for key, cls in PROVIDERS:
        display = AVAILABLE_PROVIDERS[key]
        cities = cls.get_supported_cities()
        verified = cls.verified_cities()
        if not cities:
            cities_cell = "— (station-based)"
            verified_cell = "—"
        else:
            cities_cell = str(len(cities))
            verified_cell = str(len(verified)) if verified else "—"
        lines.append(
            f"| {display} | {cities_cell} | {verified_cell} | "
            f"{_discovery_label(cls)} |"
        )
        if cities:
            city_list = ", ".join(f"`{c}`" for c in cities)
            details.append(
                f"<details>\n<summary>{display} cities ({len(cities)})</summary>\n\n"
                f"{city_list}\n\n</details>"
            )
    lines += ["", *details, "", END_MARKER]
    return "\n".join(lines) + "\n"


def update_providers_page() -> bool:
    """Rewrite the generated section; return True if the file changed."""
    page = REPO_ROOT / "docs" / "Providers.md"
    text = page.read_text(encoding="utf-8")
    pattern = re.compile(
        re.escape(START_MARKER) + r".*?" + re.escape(END_MARKER), re.DOTALL
    )
    block = build_coverage_block().rstrip("\n")
    new_text, n = pattern.subn(block, text)
    if n != 1:
        raise SystemExit(
            f"Expected exactly one generated block in {page}, found {n}. "
            "Did the markers get removed?"
        )
    if new_text == text:
        return False
    page.write_text(new_text, encoding="utf-8")
    return True


def main() -> None:
    changed = update_providers_page()
    print(f"docs/Providers.md {'updated' if changed else 'already in sync'}")


if __name__ == "__main__":
    main()
